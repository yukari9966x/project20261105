const norm = (s: string) => s.toLowerCase().replace(/\s+/g, '');

/** 질문(또는 검색어)에 맞는 대응어 묶음 */
export function synonymGroups(text: string): SynonymGroup[] {
  const t = norm(text);
  return SYNONYMS.filter((g) => g.triggers.some((w) => t.includes(norm(w))));
}

export function expand(text: string, target: 'ks' | 'kc' | 'recall'): string[] {
  const out = new Set<string>();
  for (const g of synonymGroups(text)) for (const w of g[target]) out.add(w);
  return [...out];
}
